(() => {
  'use strict';
  const toggle = document.querySelector('#admin-comments-toggle');
  const badge = document.querySelector('#admin-pending-badge');
  const panel = document.querySelector('#admin-comments-panel');
  const list = document.querySelector('#admin-comments-list');
  const filter = document.querySelector('#admin-comments-filter');
  const message = document.querySelector('#admin-comments-message');
  if (!toggle || !panel) return;

  let loggedIn = false;
  let comments = [];

  function notice(text, error = false) {
    message.hidden = !text;
    message.textContent = text;
    message.classList.toggle('notes-error', error);
  }

  async function api(path, method = 'GET', input) {
    const response = await fetch(path, {
      method, credentials: 'same-origin',
      headers: { 'Accept': 'application/json', ...(input ? { 'Content-Type': 'application/json' } : {}) },
      ...(input ? { body: JSON.stringify(input) } : {}),
    });
    if (response.status === 204) return {};
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data.error || 'Request failed.');
    return data;
  }

  function node(tag, className, text) {
    const item = document.createElement(tag);
    if (className) item.className = className;
    if (text !== undefined) item.textContent = text;
    return item;
  }

  function control(text, handler) {
    const b = node('button', 'button', text);
    b.type = 'button';
    b.addEventListener('click', handler);
    return b;
  }

  async function reload() {
    if (!loggedIn) return;
    try {
      const data = await api('/api/admin/comments');
      comments = data.comments;
      badge.hidden = !data.pendingCount;
      badge.textContent = data.pendingCount > 99 ? '99+' : data.pendingCount;
      render();
      notice('');
    } catch (error) {
      notice(error.message, true);
    }
  }

  async function action(comment, name) {
    if (name === 'delete' && !confirm('Delete this comment and any replies?')) return;
    try {
      await api('/api/admin/comments/' + encodeURIComponent(comment.id) +
        (name === 'delete' ? '' : '/' + name), name === 'delete' ? 'DELETE' : 'POST');
      await reload();
    } catch (error) {
      notice(error.message, true);
    }
  }

  function reply(card, comment) {
    const form = node('form', 'comments-admin-reply');
    const label = node('label', null, 'Reply as Remy Ellis (basic WMD)');
    const input = node('textarea');
    input.required = true;
    input.minLength = 3;
    input.maxLength = 4000;
    input.rows = 4;
    label.append(input);
    const send = node('button', 'button primary', 'Publish reply');
    send.type = 'submit';
    const cancel = control('Cancel', () => form.remove());
    form.append(label, send, cancel);
    form.addEventListener('submit', async event => {
      event.preventDefault();
      send.disabled = true;
      try {
        await api('/api/admin/comments/' + encodeURIComponent(comment.id) + '/reply', 'POST',
          { body: input.value });
        await reload();
      } catch (error) {
        notice(error.message, true);
        send.disabled = false;
      }
    });
    card.append(form);
    input.focus();
  }

  function render() {
    list.replaceChildren();
    const visible = comments.filter(c => filter.value === 'all' || c.status === filter.value);
    if (!visible.length) {
      list.append(node('p', 'notes-message', 'No comments in this category.'));
      return;
    }
    for (const item of visible) {
      const card = node('article', 'comments-admin-item');
      const top = node('div', 'comments-admin-item-head');
      top.append(node('strong', null, item.author ? 'Remy Ellis (Author)' : item.name));
      top.append(node('span', 'comments-admin-state is-' + item.status, item.status));
      const date = new Date(item.createdAt);
      top.append(node('time', null, isNaN(date) ? '' : date.toLocaleString('en-AU')));
      card.append(top);
      const title = node(item.noteUrl ? 'a' : 'span', 'comments-admin-note-link',
        item.noteTitle + (item.parentId ? ' · Reply' : ''));
      if (item.noteUrl) {
        title.href = item.noteUrl;
        title.target = '_blank';
        title.rel = 'noopener';
      }
      card.append(title);
      const content = node('div', 'comment-content note-body');
      content.innerHTML = item.html; // HTML generated by the strict comment renderer.
      card.append(content);
      const actions = node('div', 'comments-admin-actions');
      if (item.status !== 'approved') actions.append(control('Approve', () => action(item, 'approve')));
      if (item.status !== 'rejected') actions.append(control('Reject', () => action(item, 'reject')));
      if (item.status === 'approved') actions.append(control('Reply', () => reply(card, item)));
      actions.append(control('Delete', () => action(item, 'delete')));
      card.append(actions);
      list.append(card);
    }
  }

  function open() {
    filter.value = 'pending';
    panel.hidden = false;
    document.body.classList.add('comments-admin-open');
    reload();
    document.querySelector('#admin-comments-close').focus();
  }
  function close() {
    panel.hidden = true;
    document.body.classList.remove('comments-admin-open');
    toggle.focus();
  }

  toggle.addEventListener('click', open);
  document.querySelector('#admin-comments-close').addEventListener('click', close);
  document.querySelector('#admin-comments-refresh').addEventListener('click', reload);
  filter.addEventListener('change', render);
  document.addEventListener('keydown', e => { if (e.key === 'Escape' && !panel.hidden) close(); });
  document.addEventListener('notes-admin:authenticated', () => {
    loggedIn = true;
    toggle.hidden = false;
    reload();
    if (location.hash === '#comments') open();
  });
  document.addEventListener('notes-admin:signed-out', () => {
    loggedIn = false;
    toggle.hidden = true;
    panel.hidden = true;
    badge.hidden = true;
  });
  // Don't replace an in-progress moderation reply while its composer is open.
  setInterval(() => { if (loggedIn && !document.hidden && panel.hidden) reload(); }, 60000);
})();
